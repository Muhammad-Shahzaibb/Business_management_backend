-- ============================================================================
-- SUPERADMIN (central) database schema
-- ============================================================================
-- This is the schema of the ONE central Supabase project whose connection
-- string lives in the backend .env (SUPERADMIN_DATABASE_URL).
--
-- It holds:
--   * superadmins       - accounts that can open the superadmin portal
--   * organizations     - one row per tenant organization, including that
--                         organization's own Supabase credentials
--   * org_directory     - email -> organization index so login knows which
--                         tenant database to check
--
-- Applied AUTOMATICALLY by the backend on startup. Idempotent.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Superadmin portal accounts
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS superadmins (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(100) NOT NULL,
    password   VARCHAR(255) NOT NULL,           -- bcrypt hash only
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT superadmins_email_key UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- Organizations (tenants). Each organization has its own Supabase database.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS organizations (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(150) NOT NULL,
    slug             VARCHAR(100) NOT NULL,
    database_url     TEXT NOT NULL,             -- Postgres connection string of the org's Supabase project
    supabase_url     TEXT,                      -- optional https://<ref>.supabase.co
    service_role_key TEXT,                      -- optional service role key
    project_ref      TEXT,                      -- optional Supabase project ref
    status           VARCHAR(20) NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active', 'inactive')),
    created_at       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT organizations_slug_key UNIQUE (slug)
);

-- ---------------------------------------------------------------------------
-- Email -> organization directory.
-- Lets /api/auth/*/login find the right tenant database from an email alone,
-- so the login API stays email+password (no org field needed by the frontend).
-- One email may only belong to one organization (enforced by the API).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS org_directory (
    email      VARCHAR(100) NOT NULL,
    org_id     INT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    role_id    SMALLINT NOT NULL CHECK (role_id IN (1, 2)),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (email, org_id)
);

CREATE INDEX IF NOT EXISTS idx_org_directory_email ON org_directory(email);
