-- ============================================================================
-- TENANT (organization) database schema
-- ============================================================================
-- This is the schema of EVERY organization database (one free Supabase
-- project per organization). It mirrors prisma/schema.prisma exactly.
--
-- This file is applied AUTOMATICALLY by the backend:
--   * when the superadmin creates a new organization
--   * via POST /api/superadmin/organizations/{id}/reprovision
-- You normally never run it by hand.
--
-- All statements are idempotent (IF NOT EXISTS), so re-running is safe.
-- ============================================================================

-- Shared invoice number sequence (used by the invoice_no column defaults).
CREATE SEQUENCE IF NOT EXISTS invoice_seq;

-- ---------------------------------------------------------------------------
-- Users (admins and staff of ONE organization)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(100) NOT NULL,
    password    VARCHAR(255) NOT NULL,          -- bcrypt hash only
    role_id     SMALLINT NOT NULL CHECK (role_id IN (1, 2)), -- 1=Admin, 2=Staff
    created_at  TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_key UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- Categories
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    category_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT categories_category_name_key UNIQUE (category_name)
);

-- ---------------------------------------------------------------------------
-- Inventory (products)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inventory (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no     TEXT DEFAULT ('INV-'::text || lpad((nextval('invoice_seq'::regclass))::text, 6, '0'::text)),
    category       TEXT NOT NULL,
    product_name   TEXT NOT NULL,
    cost_price     DECIMAL(10,2) NOT NULL,
    quantity       INT NOT NULL,
    advance_amount DECIMAL(10,2) DEFAULT 0,
    added_by       TEXT NOT NULL,               -- users.id stored as text
    created_at     TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    entry_date     TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    edited         BOOLEAN DEFAULT FALSE
);

-- ---------------------------------------------------------------------------
-- Sales
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sales (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no       TEXT DEFAULT ('INV-'::text || lpad((nextval('invoice_seq'::regclass))::text, 6, '0'::text)),
    customer_name    TEXT NOT NULL,
    customer_address TEXT,
    customer_phone   TEXT,
    category         TEXT NOT NULL,
    product_name     TEXT NOT NULL,
    quantity         INT NOT NULL,
    cost_price       DECIMAL(10,2) NOT NULL,
    sale_price       DECIMAL(10,2) NOT NULL,
    payment_type     TEXT NOT NULL,             -- "1"=Full, "2"=Advance
    advance_amount   DECIMAL(10,2) DEFAULT 0,
    sold_by          TEXT NOT NULL,             -- users.id stored as text
    created_at       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    entry_date       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    edited           BOOLEAN DEFAULT FALSE
);

-- ---------------------------------------------------------------------------
-- Expenses (includes Khata fields)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS expenses (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no       TEXT DEFAULT ('INV-'::text || lpad((nextval('invoice_seq'::regclass))::text, 6, '0'::text)),
    material_name    TEXT NOT NULL,
    amount           DECIMAL(10,2) NOT NULL,
    payment_method   TEXT NOT NULL,             -- "1"=Full, "2"=Advance, "3"=Khata
    advance_amount   DECIMAL(10,2) DEFAULT 0,
    used             BOOLEAN DEFAULT FALSE,
    added_by         TEXT NOT NULL,             -- users.id stored as text
    created_at       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    entry_date       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    description      TEXT,
    edited           BOOLEAN DEFAULT FALSE,
    total_amount     DECIMAL(10,2),             -- Khata
    amount_taken     DECIMAL(10,2) DEFAULT 0,   -- Khata
    remaining_amount DECIMAL(10,2),             -- Khata
    payment_history  TEXT                       -- JSON string of takings
);

-- ---------------------------------------------------------------------------
-- Indexes (lookups used by the API)
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_inventory_added_by    ON inventory(added_by);
CREATE INDEX IF NOT EXISTS idx_inventory_created_at  ON inventory(created_at);
CREATE INDEX IF NOT EXISTS idx_inventory_invoice_no  ON inventory(invoice_no);
CREATE INDEX IF NOT EXISTS idx_sales_sold_by         ON sales(sold_by);
CREATE INDEX IF NOT EXISTS idx_sales_created_at      ON sales(created_at);
CREATE INDEX IF NOT EXISTS idx_sales_invoice_no      ON sales(invoice_no);
CREATE INDEX IF NOT EXISTS idx_expenses_added_by     ON expenses(added_by);
CREATE INDEX IF NOT EXISTS idx_expenses_created_at   ON expenses(created_at);
CREATE INDEX IF NOT EXISTS idx_expenses_invoice_no   ON expenses(invoice_no);
